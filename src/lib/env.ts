import { z } from "zod";

const LOOPBACK_HOSTS = new Set(["127.0.0.1", "localhost", "[::1]", "::1"]);

const optional = z
  .string()
  .optional()
  .transform((value) => (value && value.trim().length > 0 ? value.trim() : undefined));

const loopbackUrl = z
  .string()
  .url()
  .refine((value) => LOOPBACK_HOSTS.has(new URL(value).hostname), { message: "must point to 127.0.0.1 (never expose the Chrome debug port)" });

const envSchema = z.object({
  NODE_ENV: z.enum(["development", "production", "test"]).default("production"),
  /** Tests point Gemini and Meta to local fakes. */
  SIMULATION_MODE: z
    .enum(["true", "false"])
    .default("false")
    .transform((value) => value === "true"),

  OPENAI_API_KEY: optional,
  OPENAI_BASE_URL: optional.pipe(z.string().url().optional()),
  OPENAI_MODEL: z.string().min(1).default("gpt-5-mini"),
  /** Price per million tokens of OPENAI_MODEL, for the monthly ceiling ({"input":0.25,"output":2}). */
  OPENAI_PRICE_PER_MTOK: z
    .string()
    .default('{"input":0.25,"output":2}')
    .transform((raw, ctx) => {
      const parsed = z.object({ input: z.number().nonnegative(), output: z.number().nonnegative() }).safeParse(JSON.parse(raw));
      if (!parsed.success) {
        ctx.addIssue({ code: "custom", message: 'expected {"input": number, "output": number}' });
        return z.NEVER;
      }
      return parsed.data;
    }),
  OPENAI_MONTHLY_BUDGET_USD: z.coerce.number().positive().default(5),

  /** Instagram API with Instagram Login: token with instagram_business_content_publish. */
  INSTAGRAM_TOKEN: optional,
  INSTAGRAM_ACCOUNT_ID: optional,
  /**
   * Empty: chosen by the token. Instagram Login tokens (IG...) use graph.instagram.com; tokens in
   * the Facebook format (EAA..., from Facebook Login or the "Unified login" setup) use
   * graph.facebook.com with the Instagram business account ID.
   */
  INSTAGRAM_GRAPH_BASE_URL: optional.pipe(z.string().url().optional()),

  /** Chrome logged in Gemini (gemini.google.com), only on the local debug port. */
  GEMINI_CDP_URL: loopbackUrl.default("http://127.0.0.1:9236"),
  /**
   * How many Google accounts with Gemini (one Chrome each: account 1 on 9236, account 2 on 9237,
   * ...). When one reaches the daily limit or logs out, the next one is used.
   */
  GEMINI_ACCOUNTS: z.coerce.number().int().min(1).max(4).default(2),
  /** Exact Chrome addresses of the accounts, comma separated (overrides the ports above). */
  GEMINI_CDP_URLS: optional.transform((value) => value?.split(",").map((item) => item.trim()).filter(Boolean)).pipe(z.array(loopbackUrl).optional()),
  GEMINI_ORIGIN: z.string().url().default("https://gemini.google.com"),

  CONTENT_DIR: z.string().default("./content"),
  /** Public address Meta downloads the files from. Empty: the tunnel address in tunel-url.txt. */
  CONTENT_PUBLIC_BASE_URL: optional.transform((value) => value?.replace(/\/$/, "")).pipe(z.string().url().optional()),
  FFMPEG_PATH: optional,
  /** Chrome used, invisible, to draw the slides (empty: find it automatically). */
  WEB_BROWSER_PATH: optional,

  DATABASE_URL: z.string().default("file:./data/conteudo.db"),
  /** Secret that signs the public file URLs (generated by the installer). */
  STATE_ENCRYPTION_KEY: z.string().regex(/^[0-9a-f]{64}$/i, "must be 32 bytes in hex"),
  PANEL_PASSWORD: z.string().min(12, "use at least 12 characters"),
  PORT: z.coerce.number().int().default(3200),
  TIME_ZONE: z.string().default("America/Sao_Paulo"),
});

export type Env = z.infer<typeof envSchema>;

let cached: Env | undefined;

export function getEnv(): Env {
  if (cached) return cached;
  const parsed = envSchema.safeParse(process.env);
  if (!parsed.success) {
    throw new Error(`Invalid environment: ${parsed.error.issues.map((issue) => `${issue.path.join(".")}: ${issue.message}`).join("; ")}`);
  }
  if (!parsed.data.SIMULATION_MODE && new URL(parsed.data.GEMINI_ORIGIN).hostname !== "gemini.google.com") {
    throw new Error("Invalid environment: GEMINI_ORIGIN must be gemini.google.com");
  }
  cached = parsed.data;
  return cached;
}

export function resetEnvCache(): void {
  cached = undefined;
}
